export function searchCommonIngredients(typed, howMany = 8) {
  const wanted = typed.trim().toLowerCase()

  if (!wanted) {
    return []
  }

  const starting = []
  const containing = []

  for (const ingredient of COMMON_INGREDIENTS) {
    if (ingredient.startsWith(wanted)) {
      starting.push(ingredient)
    } else if (ingredient.includes(wanted)) {
      containing.push(ingredient)
    }
  }

  return [...starting, ...containing].slice(0, howMany)
}